#!/usr/bin/env python3
"""
bert_filter.py — Filter word_context.py CSV output using BERT-based classifiers.

Three classifiers run on each target_context chunk:

  1. Language — langdetect (lightweight, no neural model)
     Drops rows where English-language probability < --lang-threshold (default 0.85).

  2. Writing quality — heuristic scorer (no ML, no torch required)
     Scores based on function-word ratio, comma density, and separator density.
     Catches keyword strings, SEO spam, and nav menus without loading any model.
     Drops rows below --quality-threshold (default 0.70).

  3. Slang sense disambiguation — bert-base-uncased contextual embeddings
     Only loaded when --slang-defs is provided. Requires torch + transformers.
     Compares the word's contextual embedding to prototype vectors built from
     user-supplied example sentences in slang.yaml.
     Words with both senses: score = cos_sim(context, slang_proto) - cos_sim(context, standard_proto).
     Words with slang examples only: score = cos_sim(context, slang_proto) (0-1 absolute).
     Drops rows below --slang-threshold (default 0.0).
     Rows containing no defined slang word are not affected.

torch and transformers are only required when --slang-defs is passed.
Without it, the script runs on langdetect + pure-Python heuristics only.

"Embeddings" for slang classification are built from samples in slang.yaml.
The yaml content was generated by Claude Sonnet 4.6 and manually edited.

Usage:
    # Language + quality only (no torch needed)
    python bert_filter.py contexts/*.csv -o filtered.csv

    # All three filters (torch required)
    python bert_filter.py contexts/*.csv -o filtered.csv --slang-defs slang.yaml

    # Score everything for threshold calibration
    python bert_filter.py input.csv -o scored.csv --score-all --keep-scores \\
        --slang-defs slang.yaml

    # Stricter slang gate
    python bert_filter.py input.csv -o out.csv --slang-defs slang.yaml \\
        --slang-threshold 0.05
"""

